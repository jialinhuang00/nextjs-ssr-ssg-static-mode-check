// Copies each route's page.tsx / route.ts into src/app/sources.generated.ts, so a page can
// show its own source. It has to happen before next runs: on Cloudflare Workers a dynamic
// page renders at request time and has no file system to read from.
// Syntax colours are worked out here too, once at build, as [text, colour] pairs per line.
// Stamp also renders inside a 'use client' page (/use-client), so a highlighter called at
// render time would have to ship to the browser; precomputed colours ship as plain data.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'
import { createHighlighter } from 'shiki'

const APP = 'src/app'
const out = {}
const hl = await createHighlighter({ themes: ['github-light'], langs: ['tsx'] })
const tokens = (code) =>
  hl.codeToTokensBase(code, { lang: 'tsx', theme: 'github-light' }).map((line) => line.map((t) => [t.content, t.color]))

function file(path) {
  const code = readFileSync(path, 'utf8').trimEnd()
  return { file: relative('.', path), code, tokens: tokens(code) }
}

function walk(dir) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name)
    if (statSync(full).isDirectory()) walk(full)
    else if (name === 'page.tsx' || name === 'route.ts') {
      const route = '/' + relative(APP, dir).split('\\').join('/')
      // Other files next to the page (loading.tsx, a client component) go in extras.
      const extras = readdirSync(dir)
        .filter((f) => f !== name && /\.tsx?$/.test(f))
        .map((f) => file(join(dir, f)))
      if (route !== '/') out[route] = { ...file(full), extras }
    }
  }
}
walk(APP)

const type = `{ file: string; code: string; tokens: [string, string][][] }`
const body = `// Generated by scripts/gen-sources.mjs. Do not edit.\nexport type Source = ${type}\nexport const SOURCES: Record<string, Source & { extras: Source[] }> = ${JSON.stringify(out)}\n`
writeFileSync(join(APP, 'sources.generated.ts'), body)
console.log(`gen-sources: ${Object.keys(out).length} routes`)
