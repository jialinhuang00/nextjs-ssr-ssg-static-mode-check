// The mode label and colour the sidebar uses. /api/post has no entry in routes.ts (no UI for a
// POST), so its mode is copied from the build table: ƒ.
function modeOf(path: string): { label: string; kind: Kind } {
  const r = findRoute(path)
  return r ? { label: r.status ? String(r.status) : modeLabel(r), kind: modeKind(r) } : { label: 'ƒ Dynamic (SSR)', kind: 'dynamic' }
}

